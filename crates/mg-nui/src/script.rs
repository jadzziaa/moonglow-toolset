fn fingerprint(bytes: &[u8]) -> String {
    let mut h = 0xcbf29ce484222325u64;
    for b in bytes {
        h = (h ^ u64::from(*b)).wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

/// Encode JSON as ASCII, including surrogate pairs. NWScript source has no
/// Unicode encoding contract, while JsonParse understands Unicode escapes.
pub(crate) fn ascii_json(v: &Value) -> String {
    let text = serde_json::to_string(v).unwrap();
    let mut out = String::new();
    for ch in text.chars() {
        if ch.is_ascii() {
            out.push(ch);
        } else {
            for unit in ch.encode_utf16(&mut [0; 2]) {
                write!(out, "\\u{unit:04x}").unwrap();
            }
        }
    }
    out
}

pub(crate) fn literal(s: &str) -> String {
    serde_json::to_string(s).unwrap()
}

pub(crate) fn json_string(out: &mut String, variable: &str, v: &Value) {
    writeln!(out, "    string {variable} = \"\";").unwrap();
    // Small literals avoid NWScript token limits. Splitting may occur inside
    // a JSON escape: concatenation restores it before JsonParse is called.
    for chunk in ascii_json(v).as_bytes().chunks(512) {
        writeln!(out, "    {variable} += {};", literal(std::str::from_utf8(chunk).unwrap()))
            .unwrap();
    }
}

pub fn opener_source(name: &str, window: &Value, settings: &Settings) -> Result<String, String> {
    check_name(name)?;
    let window_id = crate::actions::string_expr(settings.window_id.as_deref().unwrap_or(name));
    let mut out = format!(
        "// Generated by Moonglow NUI. Regeneration protects manual changes.\n// Include {name}_o in your own script and call Open_{name}(oPlayer).\n// Choose the player and triggering event in that script; this file has no main.\nvoid Open_{name}(object oPlayer)\n{{\n    if (!GetIsPC(oPlayer)) return;\n"
    );
    if settings.from_resref {
        writeln!(
            out,
            "    int nToken = NuiCreateFromResRef(oPlayer, \"{name}\", {window_id}, \"{name}_e\");"
        )
        .unwrap();
    } else {
        json_string(&mut out, "sLayout", window);
        writeln!(
            out,
            "    int nToken = NuiCreate(oPlayer, JsonParse(sLayout), {window_id}, \"{name}_e\");"
        )
        .unwrap();
    }
    out.push_str("    if (nToken <= 0) return;\n");
    for (i, (bind, b)) in settings.bindings.iter().enumerate() {
        let var = format!("sBind{i}");
        // Names can also be non-ASCII. Decode them through JSON at runtime.
        json_string(&mut out, &format!("sName{i}"), &Value::String(bind.clone()));
        json_string(&mut out, &var, &b.value);
        writeln!(
            out,
            "    NuiSetBind(oPlayer, nToken, JsonGetString(JsonParse(sName{i})), JsonParse({var}));"
        )
        .unwrap();
    }
    // Watches are enabled only after *all* initial values are installed.
    for (i, (bind, b)) in settings.bindings.iter().enumerate() {
        if b.watch || settings.actions.iter().any(|a| a.event == "watch" && a.element == *bind) {
            writeln!(
                out,
                "    NuiSetBindWatch(oPlayer, nToken, JsonGetString(JsonParse(sName{i})), TRUE);"
            )
            .unwrap();
        }
    }
    out.push_str("}\n");
    // What a script switches a swap layout to: each variant, and each swap
    // layout's initial contents, rebuilt here on every Build.
    for (view, layout) in &settings.views {
        writeln!(
            out,
            "\n// Swap layout variant {}.\njson {}()\n{{",
            literal(view),
            crate::actions::variant_function(name, view)
        )
        .unwrap();
        json_string(&mut out, "sLayout", layout);
        out.push_str("    return JsonParse(sLayout);\n}\n");
    }
    for group in swap_groups(settings) {
        let initial = if group == "_window_" {
            Some(&window["root"])
        } else {
            find_group(window, &group)
                .or_else(|| settings.views.values().find_map(|v| find_group(v, &group)))
        };
        if let Some(initial) = initial {
            writeln!(
                out,
                "\n// Initial contents of swap layout {}.\njson {}()\n{{",
                literal(&group),
                crate::actions::initial_function(name, &group)
            )
            .unwrap();
            json_string(&mut out, "sLayout", initial);
            out.push_str("    return JsonParse(sLayout);\n}\n");
        }
    }
    Ok(out)
}

/// The groups variants are shown in: their remembered targets and swap hosts.
fn swap_groups(settings: &Settings) -> std::collections::BTreeSet<String> {
    let mut groups = std::collections::BTreeSet::new();
    if let Some(targets) = settings.extra.get("view_targets").and_then(Value::as_object) {
        groups.extend(targets.values().filter_map(Value::as_str).map(str::to_owned));
    }
    if let Some(hosts) = settings.extra.get("swap_hosts").and_then(Value::as_array) {
        groups.extend(hosts.iter().filter_map(Value::as_str).map(str::to_owned));
    }
    for route in &settings.actions {
        if let crate::Action::View { group, .. } = &route.action {
            groups.insert(group.clone());
        }
    }
    groups
}

/// The child of the group with this ID: what it shows first.
fn find_group<'a>(v: &'a Value, id: &str) -> Option<&'a Value> {
    match v {
        Value::Object(o) if v["type"] == "group" && v["id"] == id => o.get("children")?.get(0),
        Value::Object(o) => o.values().find_map(|v| find_group(v, id)),
        Value::Array(a) => a.iter().find_map(|v| find_group(v, id)),
        _ => None,
    }
}

pub(crate) const EVENTS: &str =
    "// Generated NUI events. No actions configured.\nvoid main()\n{\n}\n";

// Recognize only the exact old generated template when upgrading an owned script.
const LEGACY_EVENTS: &str = "// Moonglow NUI event script: preserved on regeneration; edit this file.\nvoid main()\n{\n    object oPlayer = NuiGetEventPlayer();\n    int nToken = NuiGetEventWindow();\n    string sType = NuiGetEventType();\n    string sElement = NuiGetEventElement();\n    if (sType == \"click\" && sElement == \"mg_close\")\n        NuiDestroy(oPlayer, nToken);\n    // Add click/watch handling here. List events expose NuiGetEventArrayIndex().\n}\n";

/// Script bytes as text and back, one character a byte: what a builder
/// writes between the markers comes back as it was, whatever its codepage.
fn bytes_text(b: &[u8]) -> String {
    b.iter().map(|&c| char::from(c)).collect()
}

fn text_bytes(s: &str) -> Vec<u8> {
    s.chars().map(|c| u8::try_from(u32::from(c)).unwrap_or(b'?')).collect()
}

/// The event script Build would write over `existing`: handlers rebuilt
/// around the code between their markers; a script without markers that
/// Moonglow wrote (an older version) rebuilt from the handlers; one written
/// by hand kept as it is while there are no handlers, refused otherwise.
fn events_over(
    existing: Option<&[u8]>,
    settings: &Settings,
    name: &str,
) -> Result<Vec<u8>, String> {
    let Some(b) = existing else {
        return crate::actions::event_source(name, settings).map(String::into_bytes);
    };
    let text = bytes_text(b).replace("\r\n", "\n");
    if text.contains(crate::actions::BEGIN.trim_end()) {
        if crate::actions::edited_outside(name, &text) {
            return Err(format!(
                "{name}_e.nss was changed outside its mg:begin and mg:end lines, where Build would lose it. Move that code into a handler's section, or the top one for includes and helper functions."
            ));
        }
        Ok(text_bytes(&crate::actions::merge_events(name, settings, Some(&text))?))
    } else if b == EVENTS.as_bytes()
        || b == LEGACY_EVENTS.as_bytes()
        || settings.event_hash.as_deref() == Some(&fingerprint(b))
    {
        crate::actions::event_source(name, settings).map(String::into_bytes)
    } else if settings.actions.is_empty() {
        Ok(b.to_vec())
    } else {
        Err(format!(
            "{name}_e.nss was written by hand. Rename it to keep it, or move its code between the markers of the handlers Moonglow writes."
        ))
    }
}

/// Includes event metadata and manual event edits in the editor's build status.
pub fn is_current(module: &Module, name: &str, window: &Value, settings: &Settings) -> bool {
    let Ok(opener) = opener_source(name, window, settings) else { return false };
    let script = module.get(&key(&format!("{name}_e"), ResType::NSS));
    module.get(&key(&format!("{name}_o"), ResType::NSS)) == Some(opener.as_bytes())
        && script.is_some_and(|b| {
            events_over(Some(b), settings, name).is_ok_and(|e| e == b)
                && settings.compiled_event_hash.as_deref() == Some(&fingerprint(b))
        })
        && !module.contains(&key(&format!("{name}_o"), ResType::NCS))
        && module.contains(&key(&format!("{name}_e"), ResType::NCS))
}

/// Prepare the entire change before touching the module. The official
/// compiler resolves module includes first, then the current game's resources.
/// Existing event code is retained and recompiled. An edited opener is an
/// explicit conflict, never silently overwritten. Undo restores all resources.
pub fn generate(
    module: &Module,
    name: &str,
    mut resolve: impl FnMut(&str, ResType) -> Option<Vec<u8>>,
) -> Result<Command, String> {
    check_name(name)?;
    let jui = key(name, ResType::JUI);
    let txt = key(name, ResType::TXT);
    let window = parse(module.get(&jui).ok_or_else(|| format!("Missing {jui}"))?)?;
    let mut settings = match module.get(&txt) {
        Some(b) => Settings::parse(b)?,
        None => Settings::default(),
    };
    let errors: Vec<_> = validate(&window, &settings)
        .into_iter()
        .filter(|d| d.severity == Severity::Error)
        .collect();
    if !errors.is_empty() {
        return Err(errors
            .iter()
            .map(|d| format!("{}: {}", d.path, d.message))
            .collect::<Vec<_>>()
            .join("\n"));
    }
    let opener = format!("{name}_o");
    let events = format!("{name}_e");
    let source = opener_source(name, &window, &settings)?;
    if let Some(old) = module.get(&key(&opener, ResType::NSS)) {
        if old != source.as_bytes() && settings.opener_hash.as_deref() != Some(&fingerprint(old)) {
            return Err(format!(
                "{opener}.nss was edited or belongs to another author. Preserve it and choose another NUI resource name before generating."
            ));
        }
    } else if module.contains(&key(&opener, ResType::NCS)) {
        return Err(format!("{opener}.ncs exists without its source"));
    }
    let existing = module.get(&key(&events, ResType::NSS));
    // A script with Moonglow's sections is this window's even before its
    // first Build (Edit code writes it); one without them is someone else's.
    let ours = existing.is_some_and(|b| {
        let text = bytes_text(b).replace("\r\n", "\n");
        text.contains(crate::actions::BEGIN.trim_end())
            && !crate::actions::edited_outside(name, &text)
    });
    if existing.is_some() && settings.opener_hash.is_none() && !ours {
        return Err(format!(
            "{events}.nss already exists and is not associated with this NUI project"
        ));
    }
    if existing.is_none() && module.contains(&key(&events, ResType::NCS)) {
        return Err(format!("{events}.ncs exists without its source"));
    }
    let event_source = events_over(existing, &settings, name)?;
    let mut edits = Vec::new();
    for (n, src) in [(&opener, source.as_bytes()), (&events, event_source.as_slice())] {
        // Validate the include's callable function with the installed compiler.
        // This temporary entry point is never stored or attached to the module.
        let validation_name = "__nui_validate";
        let validation_source =
            format!("#include \"{opener}\"\nvoid main() {{ Open_{name}(OBJECT_SELF); }}\n");
        let mut compiler = mg_script::Compiler::new(|asked, ty| {
            if ty == ResType::NSS {
                if n == &opener && asked.eq_ignore_ascii_case(validation_name) {
                    return Some(validation_source.as_bytes().to_vec());
                }
                if asked.eq_ignore_ascii_case(&opener) {
                    return Some(source.as_bytes().to_vec());
                }
                if asked.eq_ignore_ascii_case(&events) {
                    return Some(event_source.clone());
                }
            }
            mg_resman::ResKey::parse(asked, ty)
                .and_then(|k| module.get(&k))
                .map(<[u8]>::to_vec)
                .or_else(|| resolve(asked, ty))
        });
        let compiled = compiler
            .compile(if n == &opener { validation_name } else { n })
            .map_err(|e| e.to_string())?;
        if compiled.ncs.is_empty() {
            return Err(format!("{n}: compiler did not produce bytecode"));
        }
        edits.push(Edit::SetResource { key: key(n, ResType::NSS), data: Some(src.to_vec()) });
        // Remove a stale executable from the old generated opener atomically.
        // User-edited sources have already been rejected above; Undo restores it.
        edits.push(Edit::SetResource {
            key: key(n, ResType::NCS),
            data: (n != &opener).then_some(compiled.ncs),
        });
        // An old debug map no longer describes this bytecode.
        if module.contains(&key(n, ResType::NDB)) {
            edits.push(Edit::SetResource { key: key(n, ResType::NDB), data: None });
        }
    }
    // Scripts of yours that include the opener carry its layout in their
    // bytecode: they are compiled again, or the game would open the old one.
    let include = format!("#include \"{opener}\"").to_ascii_lowercase();
    let callers: Vec<mg_resman::ResKey> = module
        .keys()
        .filter(|k| k.restype == ResType::NSS)
        .filter(|k| {
            let n = k.resref.to_string();
            !n.eq_ignore_ascii_case(&opener) && !n.eq_ignore_ascii_case(&events)
        })
        .filter(|k| {
            module.get(k).is_some_and(|b| bytes_text(b).to_ascii_lowercase().contains(&include))
        })
        .copied()
        .collect();
    for k in callers {
        let caller = k.resref.to_string();
        let mut compiler = mg_script::Compiler::new(|asked, ty| {
            if ty == ResType::NSS && asked.eq_ignore_ascii_case(&opener) {
                return Some(source.as_bytes().to_vec());
            }
            mg_resman::ResKey::parse(asked, ty)
                .and_then(|k| module.get(&k))
                .map(<[u8]>::to_vec)
                .or_else(|| resolve(asked, ty))
        });
        // One that doesn't compile by itself (an include of yours) is left as it is.
        if let Ok(compiled) = compiler.compile(&caller)
            && !compiled.ncs.is_empty()
        {
            edits.push(Edit::SetResource {
                key: key(&caller, ResType::NCS),
                data: Some(compiled.ncs),
            });
        }
    }
    settings.opener_hash = Some(fingerprint(source.as_bytes()));
    settings.event_hash = Some(fingerprint(&event_source));
    settings.compiled_event_hash = Some(fingerprint(&event_source));
    edits.push(Edit::SetResource { key: txt, data: Some(settings.bytes()) });
    edits.retain(|e| match e {
        Edit::SetResource { key, data } => module.get(key) != data.as_deref(),
        _ => true,
    });
    Ok(Command::new(format!("Generate NUI {name}"), edits))
}
