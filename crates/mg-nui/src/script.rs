//! The scripts of a window, and Build.
//!
//! A window has two scripts. The opener (`NAME_o`) is an include with one
//! function, `Open_NAME`, that creates the window for a player and sets its
//! binds ([`opener_source`]); it is written anew by every Build, and one
//! changed by hand is not written over. The event script (`NAME_e`) is
//! rebuilt around the code in its sections ([`rebuild_events`]). Build
//! ([`generate`]) prepares both, compiles them and the module's scripts
//! that include the opener as Compile All would (`mg_module::build`), and
//! returns it all as one command: nothing of a window that fails is kept.

