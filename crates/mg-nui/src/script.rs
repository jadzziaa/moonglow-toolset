    /// A window whose events go to the module's own event script: its
    /// event script is an include with `NAME_OnEvent()`, which knows the
    /// window's events by its ID and answers TRUE for them; the opener gives
    /// the window no event script, and says the ID.
    #[test]
    fn an_event_function_is_an_include_the_module_s_script_calls() {
        let mut s = Settings { event_function: true, ..Default::default() };
        s.actions.push(Route::new("click", "mg_close", Action::Close));
        let events = crate::event_source("shop", &s).unwrap();
        assert!(events.contains("\nint shop_OnEvent()\n{\n"), "{events}");
        assert!(!events.contains("void main("), "{events}");
        assert!(
            events
                .contains("if (NuiGetWindowId(oPlayer, nToken) != WindowId_shop()) return FALSE;")
        );
        assert!(events.contains(
            "        NuiDestroy(oPlayer, nToken);\n        // mg:end\n        return TRUE;\n"
        ));
        assert!(events.ends_with("    return TRUE;\n}\n"), "{events}");
        assert!(!crate::edited_outside("shop", &events));
        let opener = opener_source("shop", &window(), &s).unwrap();
        assert!(opener.contains("NuiCreate(oPlayer, JsonParse(sLayout), \"shop\");"), "{opener}");
        assert!(opener.contains("string WindowId_shop()\n{\n    return \"shop\";\n}\n"));
        let s = Settings { from_resref: true, window_id: Some("my_shop".into()), ..s };
        let opener = opener_source("shop", &window(), &s).unwrap();
        assert!(opener.contains("NuiCreateFromResRef(oPlayer, \"shop\", \"my_shop\");"));
        assert!(opener.contains("return \"my_shop\";"));
        // A window of its own script is as it was.
        let own = opener_source("shop", &window(), &Settings::default()).unwrap();
        assert!(!own.contains("WindowId_shop"));
    }

